"""Bright stars — the alignment candidates for the phone sensor.

925 stars down to magnitude 4.5, serving two uses with different requirements.
For **aligning**, only the ~179 down to magnitude 3.0 count: it has to be
something you can find naked-eye in the finder and identify with certainty
(that is the default `max_mag` of `visible` and `nearest`). For **drawing the
map**, all of them count — without the fourth-magnitude stars the constellation
figures develop holes and the sky stops being recognisable.

The table is embedded in the source on purpose. All of `data/` is recreated by
script and may not exist; recognising the sky and aligning are the first things
you do at night, and failing there for want of a download would be failing
before starting. It is 60 KB.

Source: HYG v3 (astronexus, CC BY-SA 4.0), J2000 coordinates in degrees.
"""
