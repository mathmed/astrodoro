@dataclass(frozen=True)
class Star:
    name: str
    desig: str
    ra: float
    dec: float
    mag: float

    @property
    def label(self) -> str:
        return self.name or self.desig

    @property
    def kind_label(self) -> str:
        """Same field name as `catalog.Obj`: a star can also be a push-to
        target, and the screen should not have to know the difference."""
        return _("star, mag {mag:.1f}").format(mag=self.mag)

    @property
    def full(self) -> str:
        if self.name and self.desig:
            return f"{self.name} ({self.desig})"
        return self.label


