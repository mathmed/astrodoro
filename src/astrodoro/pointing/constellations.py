def endpoints() -> tuple[np.ndarray, np.ndarray]:
    """RA and Dec of every endpoint, in segment order (2 per segment).

    Returned flat so it fits into a single astropy transform: converting 1348
    points at once takes ~3 ms, one at a time would take seconds.
    """
    a = np.asarray(SEGMENTS, dtype=float)
    ra = np.empty(len(a) * 2)
    dec = np.empty(len(a) * 2)
    ra[0::2], dec[0::2] = a[:, 0], a[:, 1]
    ra[1::2], dec[1::2] = a[:, 2], a[:, 3]
    return ra, dec
